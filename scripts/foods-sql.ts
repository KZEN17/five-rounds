// Regenerates the shared-foods seed migration from data/foods.tsv.
// Usage: npx tsx scripts/foods-sql.ts drizzle/0002_seed_foods.sql
import { readFileSync, writeFileSync } from "node:fs";
import { foodsSeedSql, parseFoodsTsv, STAPLES } from "../src/lib/foods/tsv";

const out = process.argv[2];
if (!out) throw new Error("Pass the migration file to write.");
const foods = [...parseFoodsTsv(readFileSync("data/foods.tsv", "utf8")), ...STAPLES];
writeFileSync(out, `-- Generated by scripts/foods-sql.ts from data/foods.tsv. Re-run it rather than editing by hand.\n${foodsSeedSql(foods)}`);
console.log(`${out}: ${foods.length} foods, ${foods.filter((f) => f.needsReview).length} flagged for review`);
